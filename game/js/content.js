const WORD_PATTERN = /^[А-ЯЁ]{4,7}$/;
const LOAD_TIMEOUT_MS = 1900;

function fail(message) {
  throw new Error(`Словарь: ${message}`);
}

function textField(value, name, limit, optional = false) {
  if (optional && value === undefined) return undefined;
  if (typeof value !== 'string' || !value.trim() || value.trim().length > limit) {
    fail(`поле «${name}» должно содержать от 1 до ${limit} знаков`);
  }
  return value.trim();
}

function russianWord(value, name) {
  if (typeof value !== 'string') fail(`поле «${name}» должно быть строкой`);
  const word = normalizeWord(value);
  if (!WORD_PATTERN.test(word)) fail(`поле «${name}» должно содержать от 4 до 7 русских букв`);
  return word;
}

export function validateContent(raw) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) fail('ожидался объект');
  const version = textField(raw.version, 'version', 32);
  if (!Array.isArray(raw.words) || !raw.words.length) fail('нет слов для игры');
  if (!Array.isArray(raw.accepted) || !raw.accepted.length) fail('нет допустимых догадок');

  const ids = new Set();
  const codes = new Set();
  const answers = new Set();
  const lengths = new Set();
  const words = raw.words.map((entry) => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) fail('неверная карточка слова');
    const id = textField(entry.id, 'id', 64);
    const word = russianWord(entry.word, 'word');
    if (ids.has(id)) fail(`повторяется идентификатор ${id}`);
    const code = challengeCode(id);
    if (codes.has(code)) fail('совпали коды приглашений: измените идентификатор карточки');
    codes.add(code);
    if (answers.has(word)) fail(`повторяется ответ ${word}`);
    ids.add(id);
    answers.add(word);
    lengths.add(word.length);
    const result = {
      id,
      word,
      theme: textField(entry.theme, 'theme', 48),
      riddle: textField(entry.riddle, 'riddle', 200),
      meaning: textField(entry.meaning, 'meaning', 240),
      fact: textField(entry.fact, 'fact', 240),
    };
    const proverb = textField(entry.proverb, 'proverb', 200, true);
    if (proverb !== undefined) result.proverb = proverb;
    return result;
  });
  [4, 5, 6, 7].forEach((length) => {
    if (!lengths.has(length)) fail(`нет ответов из ${length} букв`);
  });

  const accepted = new Set(raw.accepted.map((value) => russianWord(value, 'accepted')));
  answers.forEach((word) => {
    if (!accepted.has(word)) fail(`ответ ${word} отсутствует среди допустимых догадок`);
  });
  return { version, words, accepted };
}

export async function loadContent() {
  const controller = new AbortController();
  let timeout;
  // Ограничиваем и получение ответа, и чтение JSON. Даже зависший ответ не задержит игру.
  const deadline = new Promise((resolve, reject) => {
    timeout = setTimeout(() => {
      controller.abort();
      reject(new Error('Время загрузки словаря истекло'));
    }, LOAD_TIMEOUT_MS);
  });
  const request = (async () => {
    const response = await fetch(new URL('../data/words.json', import.meta.url), {
      signal: controller.signal,
    });
    if (!response.ok) throw new Error('Словарь недоступен');
    return validateContent(await response.json());
  })();
  try {
    const content = await Promise.race([request, deadline]);
    return { ...content, fallback: false };
  } catch {
    return { ...validateContent(FALLBACK_CONTENT), fallback: true };
  } finally {
    clearTimeout(timeout);
  }
}
